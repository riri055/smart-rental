export interface SiteInfo {
  id: string;
  name: string;
  project: string;
  lat: number;
  lng: number;
  address: string;
  manager: string;
}

export interface AlertItem {
  id: string;
  assetId: string;
  assetName: string;
  equipmentType: string;
  siteId: string;
  alertType: 'Excessive Idle Time' | 'Unassigned Rented Asset' | 'Underutilization' | 'Overdue Return' | 'Return Approaching' | 'Telemetry Anomaly';
  severity: 'Critical' | 'High' | 'Medium' | 'Low';
  timestamp: string;
  description: string;
  status: 'Open' | 'Resolved';
  recommendedAction: string;
}

export interface AIRecommendation {
  id: string;
  assetId: string;
  assetName: string;
  type: string;
  confidence: number;
  sourceSite: string;
  sourceSiteName: string;
  targetSite: string;
  targetSiteName: string;
  impact: string;
  reason: string;
  status: 'Pending' | 'Applied' | 'Dismissed';
}

export interface DemandForecast {
  siteId: string;
  siteName: string;
  equipmentType: string;
  currentCount: number;
  predictedDemand: number;
  changePct: string;
  urgency: 'Critical Deficit' | 'Moderate Deficit' | 'Excess Surplus' | 'High Deficit' | 'Balanced';
  timeframe: string;
  notes: string;
}

export interface UsageLogItem {
  assetId: string;
  assetName: string;
  equipmentType: string;
  date: string;
  siteId: string;
  siteName: string;
  engineHours: number;
  idleHours: number;
  operatingHours: number;
  utilization: number;
  fuelBurnLiters: number;
}

export interface LifecycleEvent {
  id: string;
  assetId: string;
  timestamp: string;
  type: 'CHECK_OUT' | 'CHECK_IN' | 'MAINTENANCE' | 'TELEMETRY_ALERT' | 'SITE_TRANSFER' | 'AI_OPTIMIZATION';
  title: string;
  description: string;
  actor: string;
  siteId?: string;
}

